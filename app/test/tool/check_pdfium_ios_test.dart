import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/check_package.dart' show sha256Hex;

/// `tools/check-pdfium.sh --ios` (spec 028, T-028-08, CA-028-17; threat-model §5): los binarios
/// nativos que entran en la app de iOS son los fijados en `tools/ios-binaries.lock`.
///
///  - **El paquete** (siempre): `pdfium_flutter` (url y checksum de su `Package.swift` y de su
///    podspec) y `sqlite3` (`releaseTag` y las tres sumas de iOS de `asset_hashes.dart`), que el
///    script localiza con `.dart_tool/package_config.json`.
///  - **Lo compilado** (si está): el XCFramework que dejó SwiftPM en `build/ios/SourcePackages/` y las
///    descargas de SQLite del hook; con `--require-built` que falten es un fallo.
///
/// Se prueba con una copia del script y un lock de prueba en una carpeta temporal, un
/// `package_config.json` de mentira y paquetes de juguete.
const _realScript = '../tools/check-pdfium.sh';

const _url = 'https://example.invalid/PDFium-test.xcframework.zip';
const _release = 'sqlite3-9.9.9';
const _slices = ['ios-arm64', 'ios-arm64_x86_64-simulator'];
const _sqliteFiles = [
  'libsqlite3.arm64.ios.dylib',
  'libsqlite3.arm64.ios_sim.dylib',
  'libsqlite3.x64.ios_sim.dylib',
];

String _sha(String text) => sha256Hex(utf8.encode(text));

/// El mundo de prueba: script, lock, paquetes y (a gusto del test) lo compilado.
class _World {
  _World() : tmp = Directory.systemTemp.createTempSync('pdfium_ios_') {
    final tools = Directory('${tmp.path}/tools')..createSync();
    File(_realScript).copySync('${tools.path}/check-pdfium.sh');
    app = Directory('${tmp.path}/app')..createSync();
    writeLock();
    writePdfiumFlutter();
    writeSqlite3();
    writePackageConfig();
  }

  final Directory tmp;
  late final Directory app;

  String get script => '${tmp.path}/tools/check-pdfium.sh';
  String get lockPath => '${tmp.path}/tools/ios-binaries.lock';
  String get pdfiumDir => '${tmp.path}/pkgs/pdfium_flutter-9.9.9';
  String get sqliteDir => '${tmp.path}/pkgs/sqlite3-9.9.9';
  String get zipSum => _sha('zip del xcframework');

  String sliceBytes(String slice) => 'binario de $slice';
  String sqliteBytes(String file) => 'dylib $file';

  File file(String path) => File(path)..createSync(recursive: true);

  void writeLock({
    String? url,
    String? zip,
    Map<String, String>? slices,
    String? release,
    Map<String, String>? sqlite,
    bool header = true,
  }) {
    final lines = <String>[
      if (header) '# lock de prueba',
      'xcframework-url ${url ?? _url}',
      'xcframework-zip ${zip ?? zipSum}',
      for (final s in _slices) 'slice $s ${slices?[s] ?? _sha(sliceBytes(s))}',
      'sqlite3-release ${release ?? _release}',
      for (final f in _sqliteFiles)
        'sqlite3 $f ${sqlite?[f] ?? _sha(sqliteBytes(f))}',
    ];
    File(lockPath).writeAsStringSync('${lines.join('\n')}\n');
  }

  void writePdfiumFlutter({
    String? swiftUrl,
    String? swiftSum,
    String? podUrl,
    String? podSum,
  }) {
    final dir = Directory(pdfiumDir)..createSync(recursive: true);
    file('${dir.path}/darwin/pdfium_flutter/Package.swift')
        .writeAsStringSync('''
// swift-tools-version:5.6
import PackageDescription

let package = Package(
    name: "pdfium_flutter",
    targets: [
        .binaryTarget(
            name: "PDFium",
            url: "${swiftUrl ?? _url}",
            checksum: "${swiftSum ?? zipSum}"
        ),
    ]
)
''');
    file('${dir.path}/darwin/pdfium_flutter.podspec').writeAsStringSync('''
# PDFium xcframework configuration
PDFIUM_URL = "${podUrl ?? _url}"
PDFIUM_HASH = "${podSum ?? zipSum}"

Pod::Spec.new do |s|
  s.name = 'pdfium_flutter'
end
''');
  }

  void writeSqlite3({
    String? release,
    Map<String, String>? hashes,
    Set<String> omit = const {},
    bool present = true,
  }) {
    final dir = Directory(sqliteDir)..createSync(recursive: true);
    final target = File('${dir.path}/lib/src/hook/asset_hashes.dart');
    if (!present) {
      if (target.existsSync()) target.deleteSync();
      return;
    }
    file(target.path).writeAsStringSync('''
// Generated by tool/write_asset_hashes.dart
const String? releaseTag = '${release ?? _release}';

const Map<String, String> assetNameToSha256Hash = {
  'libsqlcipher.arm64.ios.dylib': '${_sha('otro')}',
${[for (final f in _sqliteFiles)
      if (!omit.contains(f)) "  '$f': '${hashes?[f] ?? _sha(sqliteBytes(f))}',"].join('\n')}
  'libsqlite3.arm64.android.so': '${_sha('android')}',
};
''');
  }

  void writePackageConfig({
    Set<String> without = const {},
    bool relative = false,
  }) {
    final pkgs = {'pdfium_flutter': pdfiumDir, 'sqlite3': sqliteDir};
    final entries = [
      for (final e in pkgs.entries)
        if (!without.contains(e.key))
          {
            'name': e.key,
            'rootUri': relative
                ? '../../pkgs/${e.value.split('/').last}'
                : Uri.directory(e.value).toString(),
            'packageUri': 'lib/',
          },
    ];
    file(
      '${app.path}/.dart_tool/package_config.json',
    ).writeAsStringSync(jsonEncode({'configVersion': 2, 'packages': entries}));
  }

  /// El XCFramework que deja SwiftPM, con los binarios de cada carpeta.
  void writeXcframework({Map<String, String>? bytes}) {
    final base =
        '${app.path}/build/ios/SourcePackages/artifacts/pdfium_flutter-9.9.9/PDFium/PDFium.xcframework';
    for (final s in _slices) {
      file('$base/$s/PDFium.framework/PDFium')
          .writeAsStringSync(bytes?[s] ?? sliceBytes(s));
    }
    // Las que no son de iOS (macOS, Catalyst) no se miran.
    file('$base/macos-arm64_x86_64/PDFium.framework/Versions/A/PDFium')
        .writeAsStringSync('de macOS');
  }

  /// Descargas de SQLite del hook (`download-<8 primeras de la suma>/libsqlite3.dylib`).
  void writeSqliteCache(String name, {String? bytes}) {
    final sum = _sha(sqliteBytes(name));
    file(
      '${app.path}/.dart_tool/hooks_runner/shared/sqlite3/build/download-${sum.substring(0, 8)}/libsqlite3.dylib',
    ).writeAsStringSync(bytes ?? sqliteBytes(name));
  }

  ProcessResult run([List<String> args = const []]) => Process.runSync('bash', [
    script,
    '--ios',
    ...args,
  ], workingDirectory: app.path);

  void dispose() => tmp.deleteSync(recursive: true);
}

String _out(ProcessResult r) => '${r.stdout}${r.stderr}';

void main() {
  late _World w;
  final skip = Process.runSync('which', ['python3']).exitCode != 0
      ? 'sin python3'
      : null;

  setUp(() => w = _World());
  tearDown(() => w.dispose());

  group('CA-028-17: los paquetes (pdfium_flutter y sqlite3)', () {
    test('CA-028-17: todo igual al lock pasa y dice qué comprobó', () {
      final r = w.run();
      expect(r.exitCode, 0, reason: _out(r));
      final text = _out(r);
      expect(text, contains('OK pdfium_flutter Package.swift y podspec'));
      expect(text, contains('OK sqlite3 releaseTag $_release'));
      for (final f in _sqliteFiles) {
        expect(text, contains('OK sqlite3 $f'));
      }
    }, skip: skip);

    test(
      'CA-028-17: la ruta relativa de package_config también se resuelve',
      () {
        w.writePackageConfig(relative: true);
        final r = w.run();
        expect(r.exitCode, 0, reason: _out(r));
      },
      skip: skip,
    );

    test('CA-028-17: otro checksum en el Package.swift falla y lo nombra', () {
      w.writePdfiumFlutter(swiftSum: _sha('otro zip'));
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('Package.swift'));
      expect(_out(r), contains('checksum'));
    }, skip: skip);

    test('CA-028-17: otra URL en el Package.swift falla', () {
      w.writePdfiumFlutter(swiftUrl: 'https://example.invalid/otro.zip');
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('Package.swift'));
      expect(_out(r), contains('url'));
    }, skip: skip);

    test('CA-028-17: otra suma en el podspec (CocoaPods) falla', () {
      w.writePdfiumFlutter(podSum: _sha('otro zip'));
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('podspec'));
    }, skip: skip);

    test('CA-028-17: otra URL en el podspec falla', () {
      w.writePdfiumFlutter(podUrl: 'https://example.invalid/otro.zip');
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('podspec'));
    }, skip: skip);

    test('CA-028-17: sin Package.swift falla (falla cerrada)', () {
      File('${w.pdfiumDir}/darwin/pdfium_flutter/Package.swift').deleteSync();
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('Package.swift'));
    }, skip: skip);

    test('CA-028-17: sin podspec falla (falla cerrada)', () {
      File('${w.pdfiumDir}/darwin/pdfium_flutter.podspec').deleteSync();
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('podspec'));
    }, skip: skip);

    test('CA-028-17: un Package.swift sin checksum falla', () {
      File('${w.pdfiumDir}/darwin/pdfium_flutter/Package.swift')
          .writeAsStringSync('// sin binaryTarget\n');
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('Package.swift'));
    }, skip: skip);

    test('CA-028-17: otra etiqueta de release de sqlite3 falla', () {
      w.writeSqlite3(release: 'sqlite3-9.9.10');
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('releaseTag'));
    }, skip: skip);

    for (final f in _sqliteFiles) {
      test('CA-028-17: otra suma de $f en sqlite3 falla y lo nombra', () {
        w.writeSqlite3(hashes: {f: _sha('cambiado')});
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains(f));
      }, skip: skip);

      test('CA-028-17: sin $f en sqlite3 falla', () {
        w.writeSqlite3(omit: {f});
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains(f));
      }, skip: skip);
    }

    test('CA-028-17: sin asset_hashes.dart falla', () {
      w.writeSqlite3(present: false);
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('asset_hashes.dart'));
    }, skip: skip);

    test('CA-028-17: un paquete que falta en package_config falla', () {
      for (final name in ['sqlite3', 'pdfium_flutter']) {
        w.writePackageConfig(without: {name});
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains('$name no está en'));
      }
    }, skip: skip);

    test('CA-028-17: un Package.swift con dos binaryTarget falla (no se '
        'elige uno)', () {
      File(
        '${w.pdfiumDir}/darwin/pdfium_flutter/Package.swift',
      ).writeAsStringSync(
        '.binaryTarget(name: "A", url: "$_url", checksum: "${w.zipSum}"),\n'
        '.binaryTarget(name: "B", url: "$_url", checksum: "${w.zipSum}"),\n',
      );
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('se esperaba un solo valor'));
    }, skip: skip);

    test('CA-028-17: sin package_config.json falla y dice qué hacer', () {
      File('${w.app.path}/.dart_tool/package_config.json').deleteSync();
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('flutter pub get'));
    }, skip: skip);

    test('CA-028-17: --package-config usa otro archivo', () {
      final other = File('${w.tmp.path}/otro.json')
        ..writeAsStringSync(
          File('${w.app.path}/.dart_tool/package_config.json')
              .readAsStringSync(),
        );
      File('${w.app.path}/.dart_tool/package_config.json').deleteSync();
      final r = w.run(['--package-config', other.path]);
      expect(r.exitCode, 0, reason: _out(r));
    }, skip: skip);
  });

  group('CA-028-17: el lock', () {
    test('CA-028-17: un lock sin una línea de cada clase falla y nombra la que falta', () {
      // (prefijo de la línea que se quita, lo que dice el error)
      for (final (key, needle) in [
        ('xcframework-url', 'no tiene xcframework-url'),
        ('xcframework-zip', 'xcframework-zip falta'),
        ('slice ios-arm64 ', 'no tiene slice ios-arm64'),
        (
          'slice ios-arm64_x86_64-simulator',
          'no tiene slice ios-arm64_x86_64-simulator',
        ),
        ('sqlite3-release', 'no tiene sqlite3-release'),
        (
          'sqlite3 libsqlite3.arm64.ios.dylib',
          'no tiene sqlite3 libsqlite3.arm64.ios.dylib',
        ),
        (
          'sqlite3 libsqlite3.arm64.ios_sim.dylib',
          'no tiene sqlite3 libsqlite3.arm64.ios_sim.dylib',
        ),
        (
          'sqlite3 libsqlite3.x64.ios_sim.dylib',
          'no tiene sqlite3 libsqlite3.x64.ios_sim.dylib',
        ),
      ]) {
        w.writeLock();
        final kept = File(w.lockPath)
            .readAsLinesSync()
            .where((l) => !l.startsWith(key))
            .join('\n');
        File(w.lockPath).writeAsStringSync('$kept\n');
        final r = w.run();
        expect(r.exitCode, 1, reason: '$key: ${_out(r)}');
        expect(_out(r), contains(needle), reason: key);
      }
    }, skip: skip);

    test('CA-028-17: una línea desconocida en el lock falla', () {
      w.writeLock();
      File(w.lockPath).writeAsStringSync(
        'xcframework-sha ${w.zipSum}\n',
        mode: FileMode.append,
      );
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('línea desconocida'));
    }, skip: skip);

    test('CA-028-17: un lock vacío o sin el archivo falla', () {
      File(w.lockPath).writeAsStringSync('# vacío\n');
      var r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      File(w.lockPath).deleteSync();
      r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('No existe'));
      expect(_out(r), contains('ios-binaries.lock'));
    }, skip: skip);

    test('CA-028-17: una suma mal formada en el lock falla (corta, en '
        'mayúsculas o con otro carácter)', () {
      for (final bad in [
        'abc',
        _sha('x').toUpperCase().replaceAll(RegExp(r'[0-9]'), 'A'),
        '${_sha('x').substring(0, 63)}g',
        '${_sha('x')}0',
      ]) {
        w.writeLock(zip: bad);
        var r = w.run();
        expect(r.exitCode, 1, reason: '$bad: ${_out(r)}');
        expect(_out(r), contains('xcframework-zip falta o no es un sha256'));
        w.writeLock(slices: {'ios-arm64': bad});
        r = w.run();
        expect(r.exitCode, 1, reason: '$bad: ${_out(r)}');
        expect(_out(r), contains('la suma de slice ios-arm64 no es un sha256'));
        w.writeLock(sqlite: {'libsqlite3.x64.ios_sim.dylib': bad});
        r = w.run();
        expect(r.exitCode, 1, reason: '$bad: ${_out(r)}');
        expect(
          _out(r),
          contains('la suma de sqlite3 libsqlite3.x64.ios_sim.dylib no es'),
        );
      }
    }, skip: skip);

    test(
      'CA-028-17: un lock con otra suma del zip no coincide con el paquete',
      () {
        w.writeLock(zip: _sha('otro'));
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains('Package.swift'));
      },
      skip: skip,
    );
  });

  group('CA-028-17: lo compilado', () {
    test(
      'CA-028-17: el XCFramework de SwiftPM con los binarios fijados pasa',
      () {
        w.writeXcframework();
        final r = w.run();
        expect(r.exitCode, 0, reason: _out(r));
        for (final s in _slices) {
          expect(_out(r), contains('OK PDFium $s'));
        }
      },
      skip: skip,
    );

    for (final s in _slices) {
      test('CA-028-17: un binario distinto en $s falla y lo nombra', () {
        w.writeXcframework(bytes: {s: 'manipulado'});
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains(s));
        expect(_out(r), contains('ios-binaries.lock'));
      }, skip: skip);

      test('CA-028-17: sin $s en un XCFramework que existe falla', () {
        w.writeXcframework();
        Directory(
          '${w.app.path}/build/ios/SourcePackages/artifacts/pdfium_flutter-9.9.9/PDFium/PDFium.xcframework/$s',
        ).deleteSync(recursive: true);
        final r = w.run();
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains(s));
      }, skip: skip);
    }

    test('CA-028-17: sin XCFramework compilado pasa con aviso, y con --require-built falla', () {
      var r = w.run();
      expect(r.exitCode, 0, reason: _out(r));
      expect(_out(r), contains('sin XCFramework compilado'));
      r = w.run(['--require-built']);
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('XCFramework'));
    }, skip: skip);

    test('CA-028-17: con --require-built, sin XCFramework falla aunque haya '
        'descargas de SQLite', () {
      w.writeSqliteCache('libsqlite3.arm64.ios_sim.dylib');
      final r = w.run(['--require-built']);
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('No hay ningún XCFramework'));
    }, skip: skip);

    test('CA-028-17: --artifacts elige otra carpeta de SwiftPM', () {
      w.writeXcframework();
      final moved = '${w.tmp.path}/otras';
      Directory('${w.app.path}/build/ios/SourcePackages/artifacts')
          .renameSync(moved);
      var r = w.run(['--require-built']);
      expect(r.exitCode, 1, reason: _out(r));
      r = w.run(['--artifacts', moved]);
      expect(r.exitCode, 0, reason: _out(r));
      expect(_out(r), contains('OK PDFium ios-arm64'));
    }, skip: skip);

    test('CA-028-17: la descarga de SQLite del hook con su suma pasa', () {
      w.writeXcframework();
      w.writeSqliteCache('libsqlite3.arm64.ios_sim.dylib');
      w.writeSqliteCache('libsqlite3.x64.ios_sim.dylib');
      final r = w.run(['--require-built']);
      expect(r.exitCode, 0, reason: _out(r));
      expect(
        _out(r),
        contains('OK sqlite3 descargado libsqlite3.arm64.ios_sim.dylib'),
      );
    }, skip: skip);

    test('CA-028-17: una descarga de SQLite cambiada falla', () {
      w.writeXcframework();
      w.writeSqliteCache('libsqlite3.arm64.ios_sim.dylib', bytes: 'manipulada');
      final r = w.run();
      expect(r.exitCode, 1, reason: _out(r));
      expect(_out(r), contains('libsqlite3.arm64.ios_sim.dylib'));
    }, skip: skip);

    test(
      'CA-028-17: con --require-built, sin ninguna descarga de SQLite falla',
      () {
        w.writeXcframework();
        final r = w.run(['--require-built']);
        expect(r.exitCode, 1, reason: _out(r));
        expect(_out(r), contains('sqlite3'));
      },
      skip: skip,
    );

    test('CA-028-17: un parámetro desconocido es un error de uso', () {
      final r = w.run(['--no-existe']);
      expect(r.exitCode, 2, reason: _out(r));
    }, skip: skip);
  });

  group('CA-028-17: Android sigue igual', () {
    test('CA-028-03: sin --ios el script no mira nada de iOS', () {
      File(w.lockPath).deleteSync();
      // Sin paquetes de Android a mano: lo único que importa es que no pida el lock de iOS.
      final r = Process.runSync('bash', [
        w.script,
      ], workingDirectory: w.app.path);
      expect(_out(r), isNot(contains('ios-binaries.lock')));
      expect(r.exitCode, 1); // el de Android, sin pdfium.lock ni APK
    }, skip: skip);
  });

  test('CA-028-17: el lock real coincide con los paquetes reales de este '
      'árbol (y con el XCFramework compilado, si lo hay)', () {
    if (skip != null || !File('.dart_tool/package_config.json').existsSync()) {
      markTestSkipped('sin flutter pub get');
      return;
    }
    final r = Process.runSync('bash', [
      File(_realScript).absolute.path,
      '--ios',
    ]);
    expect(r.exitCode, 0, reason: _out(r));
    expect(_out(r), contains('OK pdfium_flutter Package.swift'));
  });
}
