/// Deja en [store] una preparación completa (teselas, pantalla y miniatura).
StagedImage stageImage(
  MemoryAttachmentStore store,
  String id, {
  AttachmentOrigin origin = AttachmentOrigin.camera,
  int width = 4000,
  int height = 3000,
}) {
  final tiles = ImageTiles(width, height);
  for (var r = 0; r < tiles.rows; r++) {
    for (var c = 0; c < tiles.columns; c++) {
      store.putStaging(id, ImageTiles.fileName(r, c), tinyJpeg);
    }
  }
  store
    ..putStaging(id, 'screen.jpg', tinyJpeg)
    ..putStaging(id, 'thumb.jpg', tinyJpeg);
  return (
    id: id,
    origin: origin,
    width: width,
    height: height,
    byteSize: tinyJpeg.length * tiles.rows * tiles.columns,
  );
}

